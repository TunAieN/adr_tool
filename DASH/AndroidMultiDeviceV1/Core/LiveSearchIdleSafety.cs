using System.Xml.Linq;

namespace AndroidMultiDeviceV1.Core;

/// <summary>
/// Optional, session-local UiAutomator2 idle optimization for the complete
/// LIVE workflow, including discovery, room identification and Phase 5.
/// The original setting is restored only when the whole workflow tears down.
/// </summary>
public sealed class LiveSearchIdleSafety
{
    const long ExpectedDefaultMs = 10000;
    const long CandidateMs = 1000;
    readonly AppiumSession _session;
    readonly Action<string> _log;
    long _originalMs;
    bool _mayHaveChanged;
    bool _optimizedActive;
    bool _gridEvidence;
    bool _roomEvidence;
    bool _restored;

    LiveSearchIdleSafety(AppiumSession session, Action<string> log)
    {
        _session=session;
        _log=log;
    }

    readonly record struct Snapshot(int Nodes, string RootName, HashSet<string> ResourceIds);

    static Snapshot Inspect(string xml)
    {
        var doc=XDocument.Parse(xml);
        if(doc.Root is null || doc.Root.Name.LocalName.Length==0)
            throw new InvalidOperationException("Không đọc được root XML Android.");
        var nodes=doc.Descendants().ToArray();
        if(nodes.Length<30)
            throw new InvalidOperationException("Cây giao diện Android quá ít phần tử để kiểm tra an toàn.");
        var ids=nodes.Select(n=>(string?)n.Attribute("resource-id"))
            .Where(id=>!string.IsNullOrWhiteSpace(id))
            .Select(id=>id!)
            .ToHashSet(StringComparer.Ordinal);
        return new Snapshot(nodes.Length,doc.Root.Name.LocalName,ids);
    }

    static bool Similar(Snapshot baseline, Snapshot candidate)
    {
        if(!string.Equals(baseline.RootName,candidate.RootName,StringComparison.Ordinal))
            return false;
        double ratio=(double)candidate.Nodes/baseline.Nodes;
        if(ratio<0.75 || ratio>1.25)return false;
        // Screen can animate, but most stable resource IDs should still exist.
        if(baseline.ResourceIds.Count>=5)
        {
            int common=baseline.ResourceIds.Intersect(candidate.ResourceIds).Count();
            if(common<Math.Min(5,baseline.ResourceIds.Count))return false;
        }
        return true;
    }

    public static async Task<LiveSearchIdleSafety> EnableAsync(
        AppiumSession session,Action<string> log,CancellationToken ct)
    {
        var scope=new LiveSearchIdleSafety(session,log);
        await scope.EnableCoreAsync(ct);
        return scope;
    }

    async Task EnableCoreAsync(CancellationToken ct)
    {
        _originalMs=await _session.GetIdleTimeoutAsync(ct);
        if(_originalMs==CandidateMs)
        {
            var currentShape=Inspect(await _session.SourceAsync(ct));
            _optimizedActive=true;
            _log($"SAFE_IDLE_ALREADY_ACTIVE: currentMs={CandidateMs}; nodes={currentShape.Nodes}; " +
                "scope=LIVE_WORKFLOW; noSettingMutation=true");
            return;
        }
        if(_originalMs!=ExpectedDefaultMs)
            throw new InvalidOperationException(
                $"SAFE_IDLE_SKIP: idle setting={_originalMs}ms, không phải mặc định 10000ms; " +
                "không thay đổi cấu hình của phiên này.");
        var before=Inspect(await _session.SourceAsync(ct));
        _log($"SAFE_IDLE_BASELINE: nodes={before.Nodes}; rootOk=true; currentMs={_originalMs}");
        try
        {
            // Set flag BEFORE network call: a cancelled response could still
            // leave the remote session updated.
            _mayHaveChanged=true;
            await _session.SetIdleTimeoutAsync(CandidateMs,ct);
            long current=await _session.GetIdleTimeoutAsync(ct);
            if(current!=CandidateMs)
                throw new InvalidOperationException("Appium không xác nhận idle=1000ms.");
            _optimizedActive=true;
            var after=Inspect(await _session.SourceAsync(ct));
            if(!Similar(before,after))
                throw new InvalidOperationException(
                    "UI không ổn định sau đổi idle: root/node/selector khác quá mức cho phép.");
            _log($"SAFE_IDLE_APPLIED: previousMs={_originalMs}; candidateMs={CandidateMs}; " +
                $"beforeNodes={before.Nodes}; afterNodes={after.Nodes}; " +
                 "scope=LIVE_WORKFLOW; restoreAtTeardown=true");
        }
        catch
        {
            try {await RestoreAsync();}
            catch(Exception restoreError)
            {
                _log($"SAFE_IDLE_RESTORE_FAILURE: {restoreError.GetType().Name}; " +
                    "phiên phải đóng; không tiếp tục xử lý.");
            }
            throw;
        }
    }

    // Evidence is generated by the normal LIVE search engine AFTER its
    // internal UI checks. We do not infer a successful screen from elapsed time.
    public void RecordEvidence(string message)
    {
        if(message.StartsWith("LIVE_SEARCH_TAB_SELECTED: selected=true; grid=True",StringComparison.Ordinal))
        {
            _gridEvidence=true;
            _log("SAFE_IDLE_STATE_VERIFIED: phase=SEARCH_GRID; source=engine_verified_tab_and_grid");
        }
        else if(message.StartsWith("PHASE3 LIVE_ACCEPTED:",StringComparison.Ordinal))
        {
            _roomEvidence=true;
            _log("SAFE_IDLE_STATE_VERIFIED: phase=LIVE_ROOM; source=engine_verified_host_and_viewer");
        }
    }

    public async Task<bool> ValidateAcceptedRoomAsync(LiveManagerSettings config,CancellationToken ct)
    {
        if(!_gridEvidence || !_roomEvidence)
        {
            _log($"SAFE_IDLE_VALIDATION_FAIL: phase=EVIDENCE; grid={_gridEvidence}; " +
                $"liveRoom={_roomEvidence}; no continuation");
            return false;
        }
        for(int i=0;i<2;i++)
        {
            if(i>0)await Task.Delay(400,ct);
            string xml=await _session.SourceAsync(ct);
            var shape=Inspect(xml);
            var state=LiveRoomUiReader.Parse(xml);
            bool allowed=state.IsLive && !state.IsSearchGrid && !state.IsEnded &&
                !state.IsMuted && !state.IsAccessRestricted && state.Viewer.HasValue &&
                state.Viewer.Value>=config.MinimumViewers &&
                (config.MaximumViewers==0 || state.Viewer.Value<=config.MaximumViewers) &&
                LiveRoomUiReader.HostButton(xml) is not null;
            _log($"SAFE_IDLE_ROOM_CHECK: sample={i+1}/2; nodes={shape.Nodes}; " +
                $"live={state.IsLive}; grid={state.IsSearchGrid}; " +
                $"viewerPresent={state.Viewer.HasValue}; " +
                $"hostButtonPresent={LiveRoomUiReader.HostButton(xml) is not null}; " +
                $"restriction={state.IsMuted || state.IsAccessRestricted}; ok={allowed}");
            if(!allowed)return false;
        }
        _log("SAFE_IDLE_VALIDATED: grid=true; room=true; twiceConfirmed=true");
        return true;
    }

    /// <summary>
    /// Fail closed if the Appium server changed the optimized value between
    /// Phase 3 validation and the Phase 5 handoff.
    /// </summary>
    public async Task VerifyPhase5IdleAsync(CancellationToken ct)
    {
        if(_restored || !_optimizedActive)
            throw new InvalidOperationException(
                "SAFE_IDLE_PHASE5_VERIFY_FAILED: optimized idle scope is no longer active.");
        long current=await _session.GetIdleTimeoutAsync(ct);
        if(current!=CandidateMs)
            throw new InvalidOperationException(
                $"SAFE_IDLE_PHASE5_VERIFY_FAILED: currentMs={current}; expectedMs={CandidateMs}.");
        _log($"SAFE_IDLE_PHASE5_READY: currentMs={current}; verified=true; scope=LIVE_WORKFLOW");
    }

    /// <summary>
    /// Restore during workflow teardown with a NEW cancellation token (including
    /// Stop/timeout), then verify server-side read-back before session disposal.
    /// </summary>
    public async Task RestoreAsync()
    {
        if(_restored || !_mayHaveChanged)return;
        try
        {
            using var restore=new CancellationTokenSource(TimeSpan.FromSeconds(45));
            await _session.SetIdleTimeoutAsync(_originalMs,restore.Token);
            long checkedMs=await _session.GetIdleTimeoutAsync(restore.Token);
            if(checkedMs!=_originalMs)
                throw new InvalidOperationException("Không xác minh được idle setting đã khôi phục.");
            _restored=true;
            _mayHaveChanged=false;
            _optimizedActive=false;
            _log($"SAFE_IDLE_RESTORED: currentMs={checkedMs}; verified=true; teardown=true");
        }
        catch(Exception e)
        {
            _log($"SAFE_IDLE_RESTORE_FAILED: exception={e.GetType().Name}; " +
                "workflow teardown will dispose the Appium session");
            throw;
        }
    }
}
